/**
 * 这一单修的是**公共区域**还是**户内**。
 *
 * 为什么要单独判（2026-09-01 用户反馈）：
 * 报修人会连着自己的门牌一起说 ——「5511弄278号503报门口机没有反应」。
 * 503 是**他住哪儿**，不是**坏在哪儿**；门口机在单元门口，是公区设施。
 * 不判这一层的话，单子会挂到 503 室头上：统计上算成这一户的户内维修，
 * 维修工按 503 敲门也找错地方（正确的是去 278 号楼下的门口机）。
 *
 * 判定分两路，取「或」：
 *   1. 大模型（懂上下文，「我家门口的灯」不会误判成公区）——主力；
 *   2. 这里的词表兜底（没配大模型、或调不通时）——只认**明确的公区设施**，
 *      模糊词（门口、楼上、楼下）一律不认，宁可漏判也不能把户内单错判成公区。
 *
 * 漏判和误判的代价不对称：
 *   漏判 = 公区单挂到某一户，统计脏、上门找错地方；
 *   误判 = 户内单丢掉房号，维修工不知道进哪一户，**当场干不了活**。
 * 所以词表这一路刻意收得很紧。
 */

/** 明确长在公共区域的设施 / 场所。长词在前，「单元门口」不被「门口」抢先 */
const PUBLIC_AREA_WORDS: string[] = [
  // 门禁对讲这一套：报修最常见的公区故障
  '单元门口机', '门口机', '可视对讲', '楼宇对讲', '对讲机', '对讲', '单元门禁', '门禁',
  '道闸', '车闸', '闸机', '单元门', '大门', '铁门', '防盗门',
  // 垂直交通与通道
  '电梯', '扶梯', '楼道', '楼梯间', '走廊', '过道', '消防通道', '天井',
  // 公共机电
  '水泵房', '水泵', '配电房', '配电间', '配电箱', '公共照明', '路灯', '庭院灯', '楼道灯',
  '监控', '摄像头', '门岗', '门卫室', '岗亭', '传达室',
  // 公共环境
  '垃圾房', '垃圾箱房', '垃圾站', '化粪池', '窨井', '井盖', '雨水井', '污水井',
  '绿化带', '草坪', '花坛', '围墙', '围栏', '栏杆', '广场', '人行道',
  '车棚', '车库', '停车场', '地下室',
  '外墙', '外立面', '屋顶', '天台', '楼顶',
].sort((a, b) => b.length - a.length);

/**
 * 说了这些就是在说自己家里，即使句子里出现公区词也按户内算。
 * 「我家门口的灯不亮」——「门口」是他家门口，不是单元门口。
 */
const INDOOR_MARKERS: string[] = ['我家', '家里', '屋里', '户内', '入户', '家中'];

/** 户内专属场所：出现这些基本可以断定不是公区 */
const INDOOR_WORDS: string[] = [
  '厨房', '卫生间', '洗手间', '厕所', '浴室', '卧室', '客厅', '餐厅', '书房',
  '阳台', '储藏室', '阁楼', '马桶', '抽水马桶', '洗菜盆', '水槽', '热水器', '油烟机',
];

/**
 * 只看文本判断是不是公区报修。**只在大模型不可用时用**，词表刻意收得紧。
 * @returns 命中的那个词（用于日志和说明）；判不出来返回空串
 */
export function detectPublicAreaWord(text: string): string {
  const value = String(text || '');
  if (!value) return '';
  // 明说了「我家 / 家里」的一律按户内，别被句子里的「门口」带偏
  if (INDOOR_MARKERS.some((w) => value.includes(w))) return '';
  if (INDOOR_WORDS.some((w) => value.includes(w))) return '';
  return PUBLIC_AREA_WORDS.find((w) => value.includes(w)) ?? '';
}

export function isPublicAreaText(text: string): boolean {
  return !!detectPublicAreaWord(text);
}
